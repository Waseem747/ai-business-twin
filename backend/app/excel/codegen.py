"""Generate a sandbox-safe Python module equivalent to an Excel model."""
from __future__ import annotations

from collections import defaultdict
from typing import Any

from app.excel.helpers import HELPER_CODE


def _blocked_cells(inspection: dict[str, Any]) -> set[str]:
    formula_by_key = {record["key"]: record for record in inspection["formulas"]}
    blocked = set(inspection["dependency_graph"].get("blocked") or [])
    blocked.update(record["key"] for record in inspection["formulas"] if not record["translatable"])
    reverse: dict[str, set[str]] = defaultdict(set)
    for edge in inspection["dependency_graph"]["edges"]:
        reverse[edge["from"]].add(edge["to"])
    frontier = list(blocked)
    while frontier:
        node = frontier.pop()
        for dependent in reverse.get(node, set()):
            if dependent not in blocked:
                blocked.add(dependent)
                frontier.append(dependent)
    return blocked


def generate_python(inspection: dict[str, Any], *, header: str = "") -> dict[str, Any]:
    blocked = _blocked_cells(inspection)
    formulas = {record["key"]: record for record in inspection["formulas"]}
    evaluation_order = [
        key
        for key in inspection["evaluation_order"]
        if key not in blocked and formulas.get(key, {}).get("translatable")
    ]
    outputs = [
        output
        for output in inspection["output_cells"]
        if output["cell"] not in blocked and formulas.get(output["cell"], {}).get("code")
    ]
    input_aliases = inspection["input_aliases"]
    required = sorted({item["alias"] for item in input_aliases if item["required"]})

    # Only constants that the generated formulas can reach are needed.
    generated_refs = set()
    for key in evaluation_order:
        generated_refs.update(formulas[key]["references"])
    constants = {
        key: value
        for key, value in inspection["constants"].items()
        if key in generated_refs or key in {item["cell"] for item in input_aliases}
    }
    alias_map = {item["alias"]: item["cell"] for item in input_aliases}

    source_lines = [
        "# ==========================================================================",
        "# Generated by AI Business Twin - Excel Logic Conversion Engine",
        "# This module was generated from a workbook formula dependency graph.",
        "# It requires review and approval before activation in production.",
        f"# Workbook: {inspection['filename']}",
    ]
    if header:
        source_lines.append(f"# {header}")
    source_lines.extend(
        [
            "# Cell-level traceability is stored in the ExcelConversion record.",
            "# ==========================================================================",
            "",
            HELPER_CODE.strip(),
            "",
            f"_DEFAULTS = {constants!r}",
            "",
            f"_ALIASES = {alias_map!r}",
            "",
            f"_REQUIRED = {required!r}",
            "",
            f"_OUTPUTS = {{ {', '.join(repr(o['key']) + ': ' + repr(o['cell']) for o in outputs)} }}",
            "",
            "",
            "def _compute(cells):",
        ]
    )
    if not evaluation_order:
        source_lines.append("    return cells")
    for key in evaluation_order:
        record = formulas[key]
        source_lines.append(f"    # {key} | {record['label'] or 'calculation'} | source: {record['formula']}")
        source_lines.append(f"    cells[{key!r}] = _safe(lambda: {record['code']})")
    source_lines.extend(
        [
            "",
            "",
            "def calculate_cells(inputs):",
            "    cells = dict(_DEFAULTS)",
            "    values = inputs or {}",
            "    for key in values:",
            "        value = values[key]",
            "        if key in _ALIASES:",
            "            cells[_ALIASES[key]] = value",
            "        elif '!' in key:",
            "            cells[key] = value",
            "    _compute(cells)",
            "    return cells",
            "",
            "",
            "def calculate(inputs):",
            "    inputs = inputs or {}",
            "    missing = []",
            "    for name in _REQUIRED:",
            "        if name not in inputs or inputs[name] is None:",
            "            missing.append(name)",
            "    if missing:",
            "        return {'_status': 'MISSING_INPUTS', '_missing': missing}",
            "    cells = calculate_cells(inputs)",
            "    result = {'_status': 'OK'}",
            "    for name in _OUTPUTS:",
            "        result[name] = cells.get(_OUTPUTS[name])",
            "    return result",
            "",
        ]
    )
    code = "\n".join(source_lines)

    input_aliases_used = [
        {
            "alias": item["alias"],
            "label": item["label"],
            "cell": item["cell"],
            "named_range": item["named_range"],
            "required": item["required"],
            "value": item["value"],
        }
        for item in input_aliases
        if item["cell"] in generated_refs or item["cell"] in constants
    ]
    output_aliases = [
        {**output, "generated": True} for output in outputs
    ]
    warnings = []
    if inspection["has_cycles"]:
        warnings.append(
            f"Circular references detected in {len(inspection['dependency_graph']['cycles'])} cycle(s); affected cells and dependents were excluded."
        )
    if inspection["unsupported"]:
        warnings.append(
            f"{len(inspection['unsupported'])} formula(s) could not be translated and were excluded. Review the unsupported list."
        )
    if inspection["external_references"]:
        warnings.append("External workbook references were detected and excluded.")
    if not outputs:
        warnings.append("No translatable labelled output cells were identified.")
    blocked_outputs = sorted(
        output["cell"] for output in inspection["output_cells"] if output["cell"] in blocked
    )
    if blocked_outputs:
        warnings.append(f"{len(blocked_outputs)} labelled output(s) depend on unsupported or circular cells and are excluded.")

    return {
        "code": code,
        "evaluation_order": evaluation_order,
        "outputs": output_aliases,
        "inputs": input_aliases_used,
        "required_inputs": required,
        "blocked_cells": sorted(blocked),
        "blocked_outputs": blocked_outputs,
        "warnings": warnings,
        "generated_formula_count": len(evaluation_order),
        "excluded_formula_count": len(inspection["formulas"]) - len(evaluation_order),
        "line_count": len(code.splitlines()),
    }
